import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { basename, extname, resolve } from 'node:path';
import sharp from 'sharp';
import { FloatType } from 'three';
import { RGBELoader } from 'three/examples/jsm/loaders/RGBELoader.js';

const sourceRoot = resolve(process.cwd(), 'public/environments');
const cacheRoot = resolve(sourceRoot, '.generated');
const generatedModule = resolve(process.cwd(), 'src/environment-presets.generated.js');
const PREVIEW_VERSION = 8;
const title = (name) => name.replace(/[_-]+/g, ' ').replace(/\b\w/g, (letter) => letter.toUpperCase());
const legacyKeys = { 'studio_small_03_1k.hdr': 'softStudio', 'ferndale_studio_03_1k.hdr': 'rimStudio', 'kloppenheim_01_puresky_1k.hdr': 'outdoor' };

export async function previewFromFloat(data, width, height, output) {
  const rgb = Buffer.alloc(width * height * 3);
  for (let index = 0; index < width * height; index += 1) {
    for (let channel = 0; channel < 3; channel += 1) {
      const linear = Math.max(0, data[index * 4 + channel]);
      rgb[index * 3 + channel] = Math.round(255 * ((linear / (1 + linear)) ** (1 / 2.2)));
    }
  }
  await sharp(rgb, { raw: { width, height, channels: 3 } }).resize({ width: 320 }).webp({ quality: 86 }).toFile(output);
}

async function buildManifest() {
  await mkdir(cacheRoot, { recursive: true });
  const allEntries = await readdir(sourceRoot);
  const files = allEntries.filter((name) => /\.hdr$/i.test(name) && !/\.grayscale\.hdr$/i.test(name)).sort((a, b) => a.localeCompare(b));
  const presets = [{ key: 'neutral', label: '中性', url: 'neutral', thumbnailUrl: '/environments/previews/neutral.webp', exposure: 1, shadowIntensity: .75, shadowSoftness: .9 }];
  for (const file of files) {
    const extension = extname(file).toLowerCase(); const stem = basename(file, extension); const key = legacyKeys[file.toLowerCase()] ?? stem;
    const url = `/environments/${encodeURIComponent(file)}`; const thumbnailUrl = `/environments/.generated/${key}.webp`;
    const source = resolve(sourceRoot, file); const sourceStat = await stat(source); const marker = resolve(cacheRoot, `${key}.stamp`);
    let current = ''; try { current = await readFile(marker, 'utf8'); } catch { /* generate */ }
    const signature = `${PREVIEW_VERSION}:${sourceStat.size}:${sourceStat.mtimeMs}`;
    if (current !== signature) {
      const bytes = await readFile(source); const buffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
      const texture = new RGBELoader().setDataType(FloatType).parse(buffer);
      await previewFromFloat(texture.data, texture.width, texture.height, resolve(cacheRoot, `${key}.webp`));
      await writeFile(marker, signature);
    }
    const grayscaleName = `${stem}.grayscale.hdr`;
    const grayscaleUrl = allEntries.includes(grayscaleName) ? `/environments/${encodeURIComponent(grayscaleName)}` : undefined;
    presets.push({ key, label: title(stem), url, grayscaleUrl, thumbnailUrl, exposure: 1, shadowIntensity: .75, shadowSoftness: .8 });
  }
  return presets;
}

export function environmentManifestPlugin() {
  return { name: 'environment-manifest', async configResolved() { const presets = await buildManifest(); await writeFile(generatedModule, `// Generated by scripts/environment-manifest-plugin.mjs when Vite starts.\nexport default ${JSON.stringify(presets, null, 2)};\n`); } };
}
